-- 1. Buat Tabel receipts
CREATE TABLE IF NOT EXISTS public.receipts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
  product_name TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('elektronik', 'kendaraan', 'pakaian', 'perabotan', 'lainnya')),
  store_name TEXT NOT NULL,
  purchase_date DATE NOT NULL,
  warranty_months INTEGER NOT NULL CHECK (warranty_months > 0),
  image_path TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Aktifkan Row Level Security (RLS)
ALTER TABLE public.receipts ENABLE ROW LEVEL SECURITY;

-- 3. Kebijakan Keamanan (RLS Policies)

-- A. Pilihan 1 (Mode Terbuka / Development):
-- Cocok untuk pengujian cepat saat fitur autentikasi akun Supabase belum diaktifkan di client
CREATE POLICY "Allow all operations for development"
ON public.receipts
FOR ALL
USING (true)
WITH CHECK (true);

/*
-- B. Pilihan 2 (Mode Produksi dengan Supabase Auth):
-- Hapus/Nonaktifkan Kebijakan A di atas, lalu aktifkan kebijakan di bawah ini:
CREATE POLICY "Users can only access their own receipts"
ON public.receipts
FOR ALL
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);
*/

-- 4. Setup Storage Bucket untuk Foto Nota
-- Membuat bucket 'receipts' agar pengguna dapat mengunggah foto nota fisik
INSERT INTO storage.buckets (id, name, public)
VALUES ('receipts', 'receipts', true)
ON CONFLICT (id) DO NOTHING;

-- Kebijakan Storage agar foto nota bisa diunggah dan dibaca
CREATE POLICY "Allow storage access for receipts"
ON storage.objects
FOR ALL
USING (bucket_id = 'receipts')
WITH CHECK (bucket_id = 'receipts');
