-- 1. Buat Tabel profiles (Data Profil Pengguna & Integrasi Telegram)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT,
  phone TEXT,
  telegram_chat_id TEXT,
  avatar_url TEXT,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Query migrasi cepat jika tabel profiles sudah aktif sebelumnya:
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS telegram_chat_id TEXT;

-- Berikan izin akses tabel ke role anon dan authenticated
GRANT ALL ON TABLE public.profiles TO anon, authenticated, service_role;

-- Aktifkan Row Level Security (RLS) pada tabel profiles
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all profile operations for development" ON public.profiles;
CREATE POLICY "Allow all profile operations for development"
ON public.profiles
FOR ALL
USING (true)
WITH CHECK (true);

